"""KiCad project from Morph's board.json: open the carrier board in KiCad, publish it on BoardRepo.

Writes a KiCad 8/9 project (.kicad_pro, .kicad_pcb, .kicad_sch) with the same copper as
morph/board.py: one inline footprint per component (no library links) with round pads like
Morph's, every trace as a segment, and the GND pour as a B.Cu zone stored filled with Morph's
own pour polygon (fractured the way KiCad stores fills), so a headless plot matches Morph's
Gerbers and KiCad can still refill it. The schematic has one box symbol per part whose pins carry
the board's net labels, so KiCad's PCB-vs-schematic check passes. Pads cover both mask layers, so
fab outputs that KiCad (or BoardRepo) generates include solder mask, which Morph's Gerbers don't.

Morph's board coordinates are y-up (Gerber convention); KiCad is y-down, so y -> H - y.
UUIDs are derived from the board, so the same board.json always gives the same files.

Pure stdlib: the demo machine needs no KiCad. check() runs kicad-cli DRC/ERC when it exists.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
import uuid
import zipfile

PAD_D, DRILL_D = 1.6, 0.9          # mirror morph/board.py
CLEAR = 0.25
_NS = uuid.UUID("6d6f7270-6800-4b69-8361-645f77726974")

LAYERS = [(0, "F.Cu", "signal"), (31, "B.Cu", "signal"),
          (32, "B.Adhes", "user", "B.Adhesive"), (33, "F.Adhes", "user", "F.Adhesive"),
          (34, "B.Paste", "user"), (35, "F.Paste", "user"),
          (36, "B.SilkS", "user", "B.Silkscreen"), (37, "F.SilkS", "user", "F.Silkscreen"),
          (38, "B.Mask", "user"), (39, "F.Mask", "user"),
          (40, "Dwgs.User", "user", "User.Drawings"), (41, "Cmts.User", "user", "User.Comments"),
          (42, "Eco1.User", "user", "User.Eco1"), (43, "Eco2.User", "user", "User.Eco2"),
          (44, "Edge.Cuts", "user"), (45, "Margin", "user"),
          (46, "B.CrtYd", "user", "B.Courtyard"), (47, "F.CrtYd", "user", "F.Courtyard"),
          (48, "B.Fab", "user"), (49, "F.Fab", "user")]


def _q(s) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def _n(v: float) -> str:
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


class _Ids:
    """Deterministic uuids: seed + running counter."""

    def __init__(self, seed: str):
        self.seed, self.i = seed, 0

    def __call__(self) -> str:
        self.i += 1
        return f"(uuid {_q(uuid.uuid5(_NS, f'{self.seed}/{self.i}'))})"


def _sym_uuid(ref: str) -> str:
    return str(uuid.uuid5(_NS, f"symbol/{ref}"))


def _fp_name(c: dict) -> str:
    return "".join("_" if ch in ' :/\\' else ch for ch in f"{c['ref']}_{c['value']}")   # ':' would read as lib:item


def _nc(c: dict, p: dict) -> str:
    return f"unconnected-({c['ref']}-Pad{p['name']})"   # KiCad's own name for a no-connect pad


def to_kicad_pcb(board: dict, name: str = "board", title: str = "Morph carrier board") -> str:
    W, H = board["size_mm"]
    fy = lambda y: H - y  # noqa: E731
    uid = _Ids(json.dumps(board["size_mm"]) + json.dumps(board["nets"], sort_keys=True))
    net_names = list(board["nets"]) + [_nc(c, p) for c in board["components"] for p in c["pads"] if not p.get("net")]
    net_id = {k: i + 1 for i, k in enumerate(net_names)}
    o = ["(kicad_pcb", "\t(version 20240108)", '\t(generator "morph")', '\t(generator_version "0.1")',
         "\t(general (thickness 1.6) (legacy_teardrops no))", '\t(paper "A4")',
         f"\t(title_block (title {_q(title)}) (comment 1 \"Generated by Morph from board.json\"))", "\t(layers"]
    for L in LAYERS:
        o.append(f"\t\t({L[0]} {_q(L[1])} {L[2]}" + (f" {_q(L[3])}" if len(L) > 3 else "") + ")")
    o += ["\t)", "\t(setup (pad_to_mask_clearance 0) (allow_soldermask_bridges_in_footprints no))",
          '\t(net 0 "")'] + [f"\t(net {net_id[k]} {_q(k)})" for k in net_names]

    for c in board["components"]:   # footprint anchored at its first pad
        p0 = c["pads"][0]
        ax, ay = p0["x"], fy(p0["y"])
        rel = lambda x, y: (x - ax, fy(y) - ay)  # noqa: E731
        x0, y0, x1, y1 = c["outline"]
        (rx0, ry0), (rx1, ry1) = rel(x0, y1), rel(x1, y0)        # top-left / bottom-right after the flip
        if c.get("round"):                                        # silk circle spans the outline width
            r = (rx1 - rx0) / 2
            ry0, ry1 = (ry0 + ry1) / 2 - r, (ry0 + ry1) / 2 + r
        ref_at = (f"(at {_n((rx0 + rx1) / 2)} {_n((ry0 + ry1) / 2)} 0) (layer \"F.SilkS\") {uid()} "
                  "(effects (font (size 1 1) (thickness 0.15)))" if c.get("round") else
                  f"(at {_n(rx0)} {_n(ry0 - 1)} 0) (layer \"F.SilkS\") {uid()} "
                  "(effects (font (size 1 1) (thickness 0.15)) (justify left))")
        o += [f"\t(footprint {_q(_fp_name(c))}", '\t\t(layer "F.Cu")', f"\t\t{uid()}", f"\t\t(at {_n(ax)} {_n(ay)})",
              f"\t\t(property \"Reference\" {_q(c['ref'])} {ref_at})",
              f"\t\t(property \"Value\" {_q(c['value'])} (at {_n(rx0)} {_n(ry1 + 1)} 0) (layer \"F.Fab\") {uid()} "
              "(effects (font (size 1 1) (thickness 0.15)) (justify left)))",
              f"\t\t(path \"/{_sym_uuid(c['ref'])}\")", '\t\t(sheetname "Root")', f"\t\t(sheetfile {_q(name + '.kicad_sch')})",
              "\t\t(attr through_hole)"]
        if c.get("round"):
            cx, cy = (rx0 + rx1) / 2, (ry0 + ry1) / 2
            o.append(f"\t\t(fp_circle (center {_n(cx)} {_n(cy)}) (end {_n(rx1)} {_n(cy)}) "
                     f"(stroke (width 0.15) (type solid)) (fill none) (layer \"F.SilkS\") {uid()})")
        else:
            o.append(f"\t\t(fp_rect (start {_n(rx0)} {_n(ry0)}) (end {_n(rx1)} {_n(ry1)}) "
                     f"(stroke (width 0.15) (type solid)) (fill none) (layer \"F.SilkS\") {uid()})")
        px = [rel(p["x"], p["y"]) for p in c["pads"]]               # courtyard covers outline and pads
        cx0 = min([rx0] + [x - PAD_D / 2 for x, _ in px]) - 0.25
        cy0 = min([ry0] + [y - PAD_D / 2 for _, y in px]) - 0.25
        cx1 = max([rx1] + [x + PAD_D / 2 for x, _ in px]) + 0.25
        cy1 = max([ry1] + [y + PAD_D / 2 for _, y in px]) + 0.25
        o.append(f"\t\t(fp_rect (start {_n(cx0)} {_n(cy0)}) (end {_n(cx1)} {_n(cy1)}) "
                 f"(stroke (width 0.05) (type solid)) (fill none) (layer \"F.CrtYd\") {uid()})")
        for p in c["pads"]:
            dx, dy = rel(p["x"], p["y"])
            pn = p.get("net") or _nc(c, p)
            o.append(f"\t\t(pad {_q(p['name'])} thru_hole circle (at {_n(dx)} {_n(dy)}) "   # round, like the pour assumes
                     f"(size {PAD_D} {PAD_D}) (drill {DRILL_D}) (layers \"*.Cu\" \"*.Mask\") (remove_unused_layers no) "
                     f"(net {net_id[pn]} {_q(pn)}) {uid()})")
        o.append("\t)")

    o.append(f"\t(gr_rect (start 0 0) (end {_n(W)} {_n(H)}) (stroke (width 0.1) (type default)) (fill none) "
             f"(layer \"Edge.Cuts\") {uid()})")
    for t in board["traces"]:
        pts = t["points"]
        for (xa, ya), (xb, yb) in zip(pts, pts[1:]):
            o.append(f"\t(segment (start {_n(xa)} {_n(fy(ya))}) (end {_n(xb)} {_n(fy(yb))}) (width {_n(t['width'])}) "
                     f"(layer {_q(t['layer'])}) (net {net_id[t['net']]}) {uid()})")
    if "GND" in net_id:   # zone outline + Morph's pour as the stored fill; KiCad may refill it
        for zi, ring in enumerate(board.get("pour", [])):
            pts = " ".join(f"(xy {_n(x)} {_n(fy(y))})" for x, y in ring["exterior"][:-1])
            fill = " ".join(f"(xy {_n(x)} {_n(fy(y))})" for x, y in _fracture(ring["exterior"], ring.get("holes", [])))
            o += [f"\t(zone (net {net_id['GND']}) (net_name \"GND\") (layer \"B.Cu\") {uid()} (name \"GND_POUR{zi}\") "
                  f"(priority {zi})", "\t\t(hatch edge 0.5)",
                  "\t\t(connect_pads yes (clearance 0.49))",   # Morph's 0.5 mm arcs are polygons: KiCad measures 0.499
                  "\t\t(min_thickness 0.25) (filled_areas_thickness no)",
                  "\t\t(fill yes (thermal_gap 0.5) (thermal_bridge_width 0.5) (island_removal_mode 0))",
                  f"\t\t(polygon (pts {pts}))", f"\t\t(filled_polygon (layer \"B.Cu\") (pts {fill}))", "\t)"]
    o.append(")")
    return "\n".join(o) + "\n"


def _fracture(ext: list, holes: list) -> list:
    """Polygon with holes -> one hole-free ring, each hole joined to the outline by a zero-width
    keyhole cut (how KiCad stores a zone fill). Holes are taken left to right; each is bridged
    horizontally from its leftmost vertex to the nearest edge of the ring built so far."""
    out = [tuple(p) for p in ext[:-1]]
    for h in sorted((tuple(map(tuple, h[:-1])) for h in holes), key=lambda h: min(p[0] for p in h)):
        k = min(range(len(h)), key=lambda i: h[i])
        px, py = h[k]
        best = None
        for i in range(len(out)):
            (ax, ay), (bx, by) = out[i], out[(i + 1) % len(out)]
            if (ay > py) != (by > py):
                x = ax + (py - ay) * (bx - ax) / (by - ay)
                if x <= px and (best is None or x > best[0]):
                    best = (x, i)
        x, i = best
        out = out[:i + 1] + [(x, py)] + list(h[k:] + h[:k]) + [h[k], (x, py)] + out[i + 1:]
    return out


def to_kicad_sch(board: dict, name: str = "board") -> str:
    """One box symbol per component, pins named like the footprint pads, a global label on every
    connected pin and a no-connect flag on every unused one. No wires needed."""
    S = 2.54
    root = str(uuid.uuid5(_NS, "sheet/root"))
    uid = _Ids("sch" + json.dumps(board["nets"], sort_keys=True))
    font = "(effects (font (size 1.27 1.27)))"
    hide = "(effects (font (size 1.27 1.27)) (hide yes))"
    libs, body = [], []
    x_cursor, y0 = 40.64, 40.64
    for c in board["components"]:
        pads = c["pads"]
        nl = (len(pads) + 1) // 2
        hh = max(nl, len(pads) - nl) * S / 2 + S / 2     # half height
        hw = 7.62 if len(pads) > 4 else 5.08              # half width
        lib = f"Morph:{c['ref']}"
        pins = []
        for side, group in ((-1, pads[:nl]), (1, pads[nl:])):
            for i, p in enumerate(group):
                py = round((hh - S / 2 - i * S) / 1.27) * 1.27
                pins.append((p, side * (hw + S), py, 0 if side < 0 else 180))
        pin_sx = "".join(f"\n\t\t\t\t(pin passive line (at {_n(px)} {_n(py)} {a}) (length {S}) "
                         f"(name {_q(p['name'])} {font}) (number {_q(p['name'])} {font}))" for p, px, py, a in pins)
        libs.append(
            f"\t\t(symbol {_q(lib)} (pin_names (offset 1.016)) (exclude_from_sim no) (in_bom yes) (on_board yes)\n"
            f"\t\t\t(property \"Reference\" {_q(c['ref'][0])} (at 0 {_n(hh + 1.27)} 0) {font})\n"
            f"\t\t\t(property \"Value\" {_q(c['value'])} (at 0 {_n(-hh - 1.27)} 0) {font})\n"
            f"\t\t\t(property \"Footprint\" \"\" (at 0 0 0) {hide})\n"
            f"\t\t\t(property \"Datasheet\" \"\" (at 0 0 0) {hide})\n"
            f"\t\t\t(symbol {_q(c['ref'] + '_0_1')} (rectangle (start {_n(-hw)} {_n(hh)}) (end {_n(hw)} {_n(-hh)}) "
            f"(stroke (width 0.254) (type default)) (fill (type background))))\n"
            f"\t\t\t(symbol {_q(c['ref'] + '_1_1')}{pin_sx})\n\t\t)")
        sx = round((x_cursor + hw + S + 12.7) / S) * S
        sy = round((y0 + hh) / S) * S
        x_cursor = sx + hw + S + 25.4
        body.append(
            f"\t(symbol (lib_id {_q(lib)}) (at {_n(sx)} {_n(sy)} 0) (unit 1) (exclude_from_sim no) (in_bom yes) "
            f"(on_board yes) (dnp no) (uuid {_q(_sym_uuid(c['ref']))})\n"
            f"\t\t(property \"Reference\" {_q(c['ref'])} (at {_n(sx)} {_n(sy - hh - 1.27)} 0) {font})\n"
            f"\t\t(property \"Value\" {_q(c['value'])} (at {_n(sx)} {_n(sy + hh + 1.27)} 0) {font})\n"
            f"\t\t(property \"Footprint\" {_q(_fp_name(c))} (at {_n(sx)} {_n(sy)} 0) {hide})\n"
            f"\t\t(property \"Datasheet\" \"\" (at {_n(sx)} {_n(sy)} 0) {hide})\n"
            + "".join(f"\t\t(pin {_q(p['name'])} {uid()})\n" for p, *_ in pins)
            + f"\t\t(instances (project {_q(name)} (path {_q('/' + root)} (reference {_q(c['ref'])}) (unit 1))))\n\t)")
        for p, px, py, a in pins:
            x, y = sx + px, sy - py                        # symbol y-up -> sheet y-down
            if p.get("net"):
                ang, just = (180, "right") if a == 0 else (0, "left")
                body.append(f"\t(global_label {_q(p['net'])} (shape passive) (at {_n(x)} {_n(y)} {ang}) "
                            f"(effects (font (size 1.27 1.27)) (justify {just})) {uid()})")
            else:
                body.append(f"\t(no_connect (at {_n(x)} {_n(y)}) {uid()})")
    return ("(kicad_sch\n\t(version 20231120)\n\t(generator \"morph\")\n\t(generator_version \"0.1\")\n"
            f"\t(uuid {_q(root)})\n\t(paper \"A3\")\n\t(lib_symbols\n" + "\n".join(libs) + "\n\t)\n"
            + "\n".join(body) + "\n\t(sheet_instances (path \"/\" (page \"1\")))\n)\n")


def to_kicad_pro(name: str) -> str:
    """Minimal project: KiCad fills in every missing key with defaults on open."""
    return json.dumps({
        "board": {"design_settings": {"rules": {"min_clearance": CLEAR, "min_track_width": 0.2,
                                                "min_through_hole_diameter": 0.3}}},
        "meta": {"filename": f"{name}.kicad_pro", "version": 1},
        "net_settings": {
            "classes": [{"name": "Default", "clearance": CLEAR, "track_width": 0.4, "via_diameter": 0.8, "via_drill": 0.4},
                        {"name": "Power", "clearance": CLEAR, "track_width": 1.0, "via_diameter": 1.0, "via_drill": 0.5}],
            "meta": {"version": 3},
            "netclass_patterns": [{"netclass": "Power", "pattern": "GND"}, {"netclass": "Power", "pattern": "V_SERVO"}]},
    }, indent=2)


def readme(board: dict, name: str, about: dict | None = None, notes: str = "") -> str:
    """README for the project folder; BoardRepo shows it on the board page."""
    about = about or {}
    W, H = board["size_mm"]
    parts = ", ".join(f"{c['ref']} {c['value']}" for c in board["components"])
    drc = board.get("drc") or {}
    rows = [("Board", f"{W:g} x {H:g} mm, 2 layers, 1.6 mm, through-hole on a 0.1\" grid"), ("Parts", parts),
            ("Nets", ", ".join(board["nets"])), ("Morph DRC", "pass" if drc.get("pass") else f"FAIL {drc}")]
    rows += [(k, v) for k, v in about.items() if v not in (None, "")]
    cell = lambda v: str(v).replace("|", "\\|").replace("\n", " ")  # noqa: E731
    lines = [f"# {name}", "",
             "Carrier board for a force-limited gripper (servo + force-sensing resistor + MCU module), "
             "generated by [Morph](https://github.com/jim4226/A16z_Hackathon) from a one-sentence need.", "",
             "| | |", "|---|---|"] + [f"| {cell(k)} | {cell(v)} |" for k, v in rows] + [
             "", "Opens in KiCad 8 or 9. Footprints and symbols are embedded in the project (no library links). "
             "The GND pour is stored filled with Morph's own polygon (B in KiCad's PCB editor refills it). "
             "Solder it on perfboard following the layout, or have KiCad generate fab outputs (they include "
             "solder mask).", "",
             "Licensed under Apache-2.0, like the Morph repository (LICENSE)."]
    return "\n".join(lines) + "\n" + (f"\n{notes}" if notes else "")


def export(board: dict, outdir: str, name: str = "board", about: dict | None = None, notes: str = "") -> dict:
    """Write <outdir>/<name>.kicad_{pro,pcb,sch} + README.md, and <outdir>/<name>-kicad.zip (the folder,
    zipped: what boardrepo.com/upload takes). Returns paths relative to outdir."""
    os.makedirs(outdir, exist_ok=True)
    files = {f"{name}.kicad_pro": to_kicad_pro(name), f"{name}.kicad_pcb": to_kicad_pcb(board, name),
             f"{name}.kicad_sch": to_kicad_sch(board, name), "README.md": readme(board, name, about, notes)}
    lic = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "LICENSE")
    if os.path.exists(lic):   # BoardRepo shows a board with no licence file as all rights reserved
        with open(lic, encoding="utf-8") as fh:
            files["LICENSE"] = fh.read()
    for fn, text in files.items():
        with open(os.path.join(outdir, fn), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    zname = f"{name}-kicad.zip"
    with zipfile.ZipFile(os.path.join(outdir, zname), "w", zipfile.ZIP_DEFLATED) as z:
        for fn in files:
            z.write(os.path.join(outdir, fn), f"{name}/{fn}")
    return {"files": list(files), "zip": zname, "kicad_version": "8/9"}


def check(outdir: str, name: str = "board") -> dict | None:
    """kicad-cli DRC (+ schematic parity) and ERC on an exported project; None without kicad-cli.

    kicad-cli doesn't refill zones, so DRC checks the stored fill (Morph's pour). Never raises."""
    cli = shutil.which("kicad-cli")
    if not cli:
        return None
    out = {}
    try:
        with tempfile.TemporaryDirectory() as tmp:
            for kind, args in (("drc", ["pcb", "drc", "--schematic-parity", os.path.join(outdir, f"{name}.kicad_pcb")]),
                               ("erc", ["sch", "erc", "--severity-error", os.path.join(outdir, f"{name}.kicad_sch")])):
                rep = os.path.join(tmp, f"{kind}.json")
                proc = subprocess.run([cli, *args[:2], "--format", "json", "-o", rep, *args[2:]],
                                      capture_output=True, text=True, timeout=120)
                if not os.path.exists(rep):   # e.g. KiCad 7, which can't read the 8/9 format
                    return {"ok": False, "error": (proc.stderr or proc.stdout).strip()[-400:]}
                with open(rep, encoding="utf-8") as fh:
                    out[kind] = json.load(fh)
    except (subprocess.SubprocessError, OSError, ValueError) as exc:
        return {"ok": False, "error": f"{exc.__class__.__name__}: {exc}"}
    d, e = out["drc"], out["erc"]
    res = {"violations": len(d.get("violations", [])), "unconnected": len(d.get("unconnected_items", [])),
           "parity": len(d.get("schematic_parity", [])),
           "erc_errors": sum(len(s.get("violations", [])) for s in e.get("sheets", [])),
           "kicad": d.get("kicad_version")}
    res["ok"] = not (res["violations"] or res["unconnected"] or res["parity"] or res["erc_errors"])
    return res


if __name__ == "__main__":   # python -m morph.kicad board.json outdir [name]
    with open(sys.argv[1], encoding="utf-8") as fh:
        brd = json.load(fh)
    nm = sys.argv[3] if len(sys.argv) > 3 else "board"
    print(export(brd, sys.argv[2], nm))
    print(check(sys.argv[2], nm) or "kicad-cli not found: open the project in KiCad to check it")
